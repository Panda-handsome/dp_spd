# -*- coding: utf-8 -*-
"""Run GPT-based real-candidate identification from saved DP-SPD groups.

This script reuses candidate groups already generated by the WildChat MIA
pipeline. It does not regenerate dummies, reload local LMs, or change the
candidate order. The prompt follows the older GPT inference attack format:
shared prefix plus candidate suffixes, with a JSON response schema.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import random
import re
import time
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

import httpx
from openai import OpenAI


def str2bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    text = str(value).strip().lower()
    if text in {"true", "1", "yes", "y"}:
        return True
    if text in {"false", "0", "no", "n"}:
        return False
    raise argparse.ArgumentTypeError(f"Invalid boolean value: {value!r}")


def get_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run GPT attack from existing WildChat DP-SPD candidate groups."
    )
    parser.add_argument(
        "--groups_jsonl",
        type=str,
        required=True,
        help="Comma-separated MIA-generated *_groups.jsonl files.",
    )
    parser.add_argument("--output_dir", type=str, default="outputs/wildchat_dpspd_blackbox_gpt_attack")
    parser.add_argument("--output_prefix", type=str, default="wildchat_gpt4o_mini_attack_from_groups")
    parser.add_argument("--gpt_model", type=str, default="gpt-4o-mini")
    parser.add_argument("--gpt_temperature", type=float, default=0.0)
    parser.add_argument("--gpt_max_completion_tokens", type=int, default=900)
    parser.add_argument("--gpt_max_retries", type=int, default=5)
    parser.add_argument("--gpt_retry_sleep_seconds", type=float, default=5.0)
    parser.add_argument("--gpt_retry_backoff_multiplier", type=float, default=2.0)
    parser.add_argument("--gpt_retry_jitter_seconds", type=float, default=1.0)
    parser.add_argument("--openai_timeout_seconds", type=float, default=180.0)
    parser.add_argument("--openai_connect_timeout_seconds", type=float, default=20.0)
    parser.add_argument("--openai_base_url", type=str, default=None)
    parser.add_argument("--api_key_env", type=str, default="OPENAI_API_KEY")
    parser.add_argument("--inter_request_sleep_seconds", type=float, default=0.5)
    parser.add_argument("--max_groups", type=int, default=0, help="0 means all groups.")
    parser.add_argument("--subsets", type=str, default="answerable_qa,open_ended")
    parser.add_argument("--save_prompts", type=str2bool, default=True)
    parser.add_argument("--resume", type=str2bool, default=True)
    parser.add_argument("--dry_run", type=str2bool, default=False)
    parser.add_argument("--dry_run_print_groups", type=int, default=1)
    return parser


def parse_csv_list(text: str) -> List[str]:
    return [part.strip() for part in str(text).split(",") if part.strip()]


def normalize_text(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "")).strip().lower()


def strip_code_fence(text: str) -> str:
    cleaned = str(text or "").strip()
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```[a-zA-Z0-9_-]*\n?", "", cleaned)
        cleaned = re.sub(r"\n?```$", "", cleaned)
    return cleaned.strip()


def parse_json_response(text: str) -> Dict[str, Any]:
    cleaned = strip_code_fence(text)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", cleaned, flags=re.DOTALL)
        if not match:
            raise
        return json.loads(match.group(0))


def safe_filename(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_.-]+", "_", text)[:180]


def row_key(row: Dict[str, Any]) -> Tuple[str, str, str]:
    return (str(row.get("_source_groups_jsonl", "")), str(row.get("subset", "")), str(row.get("id", "")))


def load_groups(paths: Sequence[str], subsets: Sequence[str], max_groups: int) -> List[Dict[str, Any]]:
    selected_subsets = set(subsets)
    rows: List[Dict[str, Any]] = []
    for path_text in paths:
        path = Path(path_text)
        with open(path, encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                row = json.loads(line)
                if row.get("attack_mode") != "mia":
                    continue
                if selected_subsets and row.get("subset") not in selected_subsets:
                    continue
                row["_source_groups_jsonl"] = str(path)
                rows.append(row)
                if max_groups > 0 and len(rows) >= max_groups:
                    return rows
    return rows


def load_completed(path: Path) -> set[Tuple[str, str, str]]:
    keys: set[Tuple[str, str, str]] = set()
    if not path.exists():
        return keys
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            keys.add(row_key(json.loads(line)))
    return keys


def build_group_attack_prompt(shared_prefix_text: str, candidate_suffix_texts: List[str]) -> str:
    candidate_block = []
    for idx, suffix in enumerate(candidate_suffix_texts):
        candidate_block.append(f"Candidate {idx} suffix:\n{suffix}")
    rendered_candidates = "\n\n".join(candidate_block)

    return f"""You are performing a GPT inference attack adapted from InferDPT.

Context:
- A privacy-preserving inference system produced one group of candidate queries.
- Exactly one candidate is the real user query.
- The other candidates are dummy continuations generated from the same shared prefix.
- The text you see below was reconstructed from noised embeddings, so it may contain token errors.

Your tasks:
1. Decide which candidate suffix is most likely to come from the real query.
2. Recover the most likely original full query before noise.
3. Briefly explain which semantic or stylistic cues made that candidate more plausible than the others.

Return valid JSON only in the following schema:
{{
  "predicted_real_index": 0,
  "recovered_query": "full recovered query here",
  "confidence": 0.0,
  "brief_reasoning": "short explanation"
}}

Shared prefix:
{shared_prefix_text}

Candidate suffixes:
{rendered_candidates}
"""


def build_client(args) -> OpenAI:
    api_key = os.environ.get(args.api_key_env)
    if not api_key:
        raise ValueError(
            f"Environment variable {args.api_key_env} is not set. "
            "Set it before running GPT attack or use --dry_run true."
        )
    kwargs = {
        "api_key": api_key,
        "max_retries": 0,
        "timeout": httpx.Timeout(
            timeout=args.openai_timeout_seconds,
            connect=args.openai_connect_timeout_seconds,
        ),
    }
    if args.openai_base_url:
        kwargs["base_url"] = args.openai_base_url
    return OpenAI(**kwargs)


def call_gpt_attack(client: OpenAI, prompt: str, args) -> Dict[str, Any]:
    last_error: Optional[Exception] = None
    for attempt in range(1, args.gpt_max_retries + 1):
        try:
            response = client.chat.completions.create(
                model=args.gpt_model,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You are a careful security research assistant. "
                            "Follow the user instructions exactly and respond with valid JSON only."
                        ),
                    },
                    {"role": "user", "content": prompt},
                ],
                temperature=args.gpt_temperature,
                max_completion_tokens=args.gpt_max_completion_tokens,
                response_format={"type": "json_object"},
            )
            content = response.choices[0].message.content or "{}"
            usage = getattr(response, "usage", None)
            parsed = parse_json_response(content)
            parsed["_raw_response_text"] = content
            parsed["_usage"] = {
                "prompt_tokens": getattr(usage, "prompt_tokens", None) if usage is not None else None,
                "completion_tokens": getattr(usage, "completion_tokens", None) if usage is not None else None,
                "total_tokens": getattr(usage, "total_tokens", None) if usage is not None else None,
            }
            return parsed
        except Exception as exc:
            last_error = exc
            if attempt >= args.gpt_max_retries:
                break
            delay = args.gpt_retry_sleep_seconds * (args.gpt_retry_backoff_multiplier ** (attempt - 1))
            if args.gpt_retry_jitter_seconds > 0:
                delay += random.uniform(0.0, args.gpt_retry_jitter_seconds)
            print(f"[OpenAI Retry] {type(exc).__name__}: {exc}. Sleeping {delay:.1f}s...")
            time.sleep(delay)
    assert last_error is not None
    raise last_error


def lcs_len(a: Sequence[str], b: Sequence[str]) -> int:
    if not a or not b:
        return 0
    prev = [0] * (len(b) + 1)
    for token_a in a:
        cur = [0]
        for j, token_b in enumerate(b, start=1):
            cur.append(prev[j - 1] + 1 if token_a == token_b else max(prev[j], cur[-1]))
        prev = cur
    return prev[-1]


def token_f1(prediction: str, reference: str) -> float:
    pred = normalize_text(prediction).split()
    ref = normalize_text(reference).split()
    if not pred or not ref:
        return 0.0
    lcs = lcs_len(pred, ref)
    precision = lcs / len(pred)
    recall = lcs / len(ref)
    if precision + recall == 0:
        return 0.0
    return 2 * precision * recall / (precision + recall)


def summarize(outputs_path: Path, summary_path: Path) -> None:
    rows: List[Dict[str, Any]] = []
    if outputs_path.exists():
        with open(outputs_path, encoding="utf-8") as f:
            rows = [json.loads(line) for line in f if line.strip()]
    fields = [
        "source_groups_jsonl",
        "dummy_k",
        "epsilon_non_sensitive",
        "epsilon_private",
        "subset",
        "group",
        "groups",
        "random_baseline",
        "gpt_selection_asr",
        "recovered_query_exact_match",
        "recovered_query_token_f1",
        "avg_confidence",
        "avg_projection_token_accuracy",
        "total_projection_changed_tokens",
        "projection_changed_samples",
        "total_prompt_tokens",
        "total_completion_tokens",
    ]
    with open(summary_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        source_paths = sorted({str(row.get("_source_groups_jsonl", "")) for row in rows})
        for source in source_paths:
            source_rows = [row for row in rows if str(row.get("_source_groups_jsonl", "")) == source]
            for subset in ["answerable_qa", "open_ended", "all"]:
                subset_rows = source_rows if subset == "all" else [row for row in source_rows if row.get("subset") == subset]
                for group in ["all", "privacy_signal", "nonprivacy"]:
                    if group == "privacy_signal":
                        group_rows = [row for row in subset_rows if bool(row.get("privacy_signal"))]
                    elif group == "nonprivacy":
                        group_rows = [row for row in subset_rows if not bool(row.get("privacy_signal"))]
                    else:
                        group_rows = list(subset_rows)
                    if not group_rows:
                        continue
                    dummy_k = int(group_rows[0].get("dummy_k", 0) or 0)
                    random_baseline = 1.0 / max(dummy_k + 1, 1)
                    confidences = [
                        float(row.get("gpt_confidence"))
                        for row in group_rows
                        if row.get("gpt_confidence") is not None
                    ]
                    usage = [row.get("gpt_usage") or {} for row in group_rows]
                    projection_acc = [float(row.get("avg_projection_token_accuracy", 0.0) or 0.0) for row in group_rows]
                    writer.writerow(
                        {
                            "source_groups_jsonl": source,
                            "dummy_k": dummy_k,
                            "epsilon_non_sensitive": f"{float(group_rows[0].get('epsilon_non_sensitive', 0.0)):.4f}",
                            "epsilon_private": f"{float(group_rows[0].get('epsilon_private', 0.0)):.4f}",
                            "subset": subset,
                            "group": group,
                            "groups": len(group_rows),
                            "random_baseline": f"{random_baseline:.6f}",
                            "gpt_selection_asr": (
                                f"{sum(float(row.get('gpt_selection_correct', 0.0)) for row in group_rows) / len(group_rows):.6f}"
                            ),
                            "recovered_query_exact_match": (
                                f"{sum(float(row.get('recovered_query_exact_match', 0.0)) for row in group_rows) / len(group_rows):.6f}"
                            ),
                            "recovered_query_token_f1": (
                                f"{sum(float(row.get('recovered_query_token_f1', 0.0)) for row in group_rows) / len(group_rows):.6f}"
                            ),
                            "avg_confidence": f"{sum(confidences) / len(confidences):.4f}" if confidences else "",
                            "avg_projection_token_accuracy": (
                                f"{sum(projection_acc) / len(projection_acc):.6f}" if projection_acc else ""
                            ),
                            "total_projection_changed_tokens": (
                                sum(int(row.get("total_projection_changed_tokens", 0) or 0) for row in group_rows)
                            ),
                            "projection_changed_samples": (
                                sum(int(row.get("projection_changed_samples", 0) or 0) for row in group_rows)
                            ),
                            "total_prompt_tokens": sum(int(u.get("prompt_tokens") or 0) for u in usage),
                            "total_completion_tokens": sum(int(u.get("completion_tokens") or 0) for u in usage),
                        }
                    )


def main() -> None:
    args = get_parser().parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    prompts_dir = output_dir / f"{args.output_prefix}_prompts"
    prompts_dir.mkdir(parents=True, exist_ok=True)
    outputs_path = output_dir / f"{args.output_prefix}_groups.jsonl"
    summary_path = output_dir / f"{args.output_prefix}_summary.csv"
    config_path = output_dir / f"{args.output_prefix}_config.json"

    paths = parse_csv_list(args.groups_jsonl)
    subsets = parse_csv_list(args.subsets)
    groups = load_groups(paths, subsets, args.max_groups)
    with open(config_path, "w", encoding="utf-8") as f:
        json.dump({"args": vars(args), "input_groups_jsonl": paths}, f, ensure_ascii=False, indent=2)

    if not args.resume:
        for path in (outputs_path, summary_path):
            if path.exists():
                path.unlink()
    completed = load_completed(outputs_path) if args.resume else set()
    client = None if args.dry_run else build_client(args)
    printed = 0

    for row in groups:
        key = row_key(row)
        if key in completed:
            print(f"[Skip] source={Path(key[0]).name} subset={key[1]} id={key[2]}")
            continue

        candidates = sorted(row.get("candidates", []), key=lambda item: int(item.get("candidate_index", 0)))
        suffixes = [str(candidate.get("projected_suffix_text", "")) for candidate in candidates]
        prompt = build_group_attack_prompt(str(row.get("shared_prefix_text", "")), suffixes)
        if args.save_prompts:
            prompt_name = safe_filename(f"{Path(row['_source_groups_jsonl']).stem}_{row.get('subset')}_{row.get('id')}")
            with open(prompts_dir / f"{prompt_name}.txt", "w", encoding="utf-8") as f:
                f.write(prompt)

        if args.dry_run:
            if printed < args.dry_run_print_groups:
                print("\n" + "=" * 80)
                print(f"[Dry Run] source={Path(row['_source_groups_jsonl']).name} subset={row.get('subset')} id={row.get('id')}")
                print(prompt[:5000])
                printed += 1
            if printed >= args.dry_run_print_groups:
                break
            continue

        assert client is not None
        result = call_gpt_attack(client, prompt, args)
        try:
            predicted = int(result.get("predicted_real_index", -1))
        except (TypeError, ValueError):
            predicted = -1
        actual = int(row.get("actual_real_index", -1))
        recovered = str(result.get("recovered_query", "")).strip()
        real_query = str(row.get("real_query", "")).strip()
        record = dict(row)
        record.update(
            {
                "attack_mode": "gpt_attack_from_groups",
                "gpt_model": args.gpt_model,
                "gpt_predicted_real_index": predicted,
                "gpt_selection_correct": float(predicted == actual),
                "recovered_query": recovered,
                "recovered_query_exact_match": float(normalize_text(recovered) == normalize_text(real_query)),
                "recovered_query_token_f1": token_f1(recovered, real_query),
                "gpt_confidence": result.get("confidence"),
                "gpt_brief_reasoning": result.get("brief_reasoning"),
                "gpt_raw_response": result.get("_raw_response_text"),
                "gpt_usage": result.get("_usage", {}),
            }
        )
        with open(outputs_path, "a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
        completed.add(key)
        print(
            f"[GPT Attack] source={Path(row['_source_groups_jsonl']).name} "
            f"subset={row.get('subset')} id={row.get('id')} pred={predicted} actual={actual} "
            f"ok={record['gpt_selection_correct']}"
        )
        if args.inter_request_sleep_seconds > 0:
            time.sleep(args.inter_request_sleep_seconds)

    summarize(outputs_path, summary_path)
    print(f"[Outputs] {outputs_path}")
    print(f"[Summary] {summary_path}")
    print(f"[Config] {config_path}")


if __name__ == "__main__":
    main()
